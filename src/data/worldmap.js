/* Antarctique : calotte générée pour éviter une longue liste de points */
export function antarcticRing(){
  const pts = [];
  for(let lon=-180; lon<=180; lon+=15){
    const wob = Math.sin(lon*0.045)*3.5 + Math.cos(lon*0.11)*2.2;
    pts.push([lon, -68 + wob]);
  }
  for(let lon=180; lon>=-180; lon-=30) pts.push([lon, -89]);
  return pts;
}
